#!/usr/bin/env python3
"""Generate bilingual formal-study text and a paired counterexample receipt."""

from csv import DictReader
from statistics import fmean

from study import ROOT, freeze, read, sha, write


NAMES={'floor26_ordinary':('普通四房','ordinary'), 'floor26_branch':('分支枢纽','branch'),
       'floor26_corridor':('长走廊','corridor'), 'floor26_loop':('环路','loop')}


def pp(value):
    return '缺失' if value is None else f'{100*value:+.2f}'


def describe(metrics, key, scale, unit):
    cell=metrics.get(key)
    if not cell:
        return 'n=0'
    average=cell['mean']*scale
    minimum=cell['minimum']*scale
    maximum=cell['maximum']*scale
    return f'{average:+.2f} [{minimum:+.2f}, {maximum:+.2f}] {unit}, n={cell["n"]}'


def main():
    output=ROOT/'results/formal'
    study=read(output/'summary.json')
    assert study['status']=='evaluated' and study['run_freeze_sha256']==sha(freeze('formal'))
    rows=study['episodes']
    results={(r['layout'],r['arm']):r for r in rows}
    lookup={(r['layout'],r['contrast']):r for r in study['contrasts']}
    aggregates=study['contrast_aggregates']
    registered=read(ROOT/'FORMAL_PROTOCOL.json')['layouts']
    labels={'joint_vs_original':('联合对原系统','joint vs. original'),
            'joint_vs_frontier':('联合对严格前沿','joint vs. frontier'),
            'global_main':('全局主效应','regional main effect'),
            'local_given_original':('原全局上的类别增量','local given original global'),
            'local_given_regional':('区域全局上的类别增量','local given regional global'),
            'interaction':('交互','interaction')}
    contrasts=[name for name in labels if name in aggregates]
    paired=[r for layout in registered if (r:=lookup.get((layout,'joint_vs_original'),{})).get('delta_J') is not None]
    counter=min(paired,key=lambda r:r['delta_J']) if paired else None
    report={'run_freeze_sha256':sha(freeze('formal')),'summary_sha256':sha(output/'summary.json'),
            'selected_counterexample_rule':'lowest observed combined-minus-original terminal J among all official building pairs',
            'minimum_pair':counter,'actual_closed_episodes':study['complete_endpoints']}
    if counter:
        layout=counter['layout']
        report['minimum_pair_episodes']={arm:results[layout,arm] for arm in ('original_G','region_S')}
        report['minimum_pair_divergence']=[p for p in study['pairs'] if p.get('layout')==layout
                 and {p.get('arm_a'),p.get('arm_b')}=={'original_G','region_S'}]
        arms=report['minimum_pair_episodes']
        with (output/'decisions.csv').open(newline='') as stream:
            report['minimum_pair_first_dispatch']={
                row['arm']:row for row in DictReader(stream)
                if row['layout']==layout and row['arm'] in arms and row['first_dispatched_paid']=='1'
            }
        with (output/'checkpoints.csv').open(newline='') as stream:
            first_clock={row['arm']:float(row['J']) for row in DictReader(stream)
                         if row['layout']==layout and row['arm'] in arms and row['actual_paid']=='48' and row['J']}
        if len(first_clock)==2:
            report['minimum_pair_J_delta_paid_48']=first_clock['region_S']-first_clock['original_G']
    destination=output/'interpretation_receipt.json'
    if destination.exists():
        assert read(destination)==report, 'The saved interpretation was generated by a different revision.'
    else:
        write(destination,report)

    complete=study['complete_endpoints']
    returns=sum(r.get('returned') is True for r in rows)
    collisions=sum(r.get('collisions') or 0 for r in rows)
    delta=[p['delta_J'] for p in paired]
    range_str=f'{pp(min(delta))} 至 {pp(max(delta))}' if delta else '缺失'
    mean=pp(fmean(delta)) if delta else '缺失'
    gate=aggregates['joint_vs_original']['map_effect_threshold_met']
    zh=['# 冻结楼层试验结果','',
        f'我们在四个留出楼层中各运行五种策略。同一楼层的五种策略共用首帧，各自执行最多 192 个计费动作，含返航。实测完成 {complete}/20 轮，'
        f'共 {returns} 轮返航、{collisions} 次模拟碰撞。联合方案相对原全局与几何局部的终点 J 平均差为 {mean} 个百分点，'
        f'逐栋范围为 {range_str} 个百分点。'+('结果达到预登记的改善标准。' if gate is True else
         '结果未达到预登记的改善标准。' if gate is False else '现有测量不足以判断是否达到预登记的改善标准。'),'']
    en=['# Frozen floor comparison','',
        f'Five arms started from the same initial sensor packet in each of four held-out floors. '
        f'The 192-action cap included the return. We measured {complete}/20 terminal maps, with {returns} returns and '
        f'{collisions} simulated collisions. The mean terminal joint map quality change for the combined method versus '
        f'the original global and tuned geometric local baseline was {mean} percentage points. '
        f'The registered engineering criterion was '+('met.' if gate is True else 'not met.' if gate is False else 'not assessable.'),'']
    primary=aggregates['joint_vs_original']['metrics']
    if 'C_free' in primary and 'F1_scene_05cm' in primary:
        cover=pp(primary['C_free']['mean'])
        surface=pp(primary['F1_scene_05cm']['mean'])
        zh.extend([f'组成指标中，正确自由区覆盖率平均变化 {cover} 个百分点，'
                   f'全场景表面 F1@5 cm 平均变化 {surface} 个百分点。',''])
        en.extend([f'Mean correct free-space coverage changed by {cover} percentage points, '
                   f'and mean whole-scene surface F1 at 5 cm changed by {surface} percentage points.',''])
    for lang,body in enumerate((zh,en)):
        heading='楼层' if lang==0 else 'Floor'
        body.append('| '+' | '.join([heading,*(labels[c][lang] for c in contrasts)])+' |')
        body.append('| '+' | '.join(['---',*['---:']*len(contrasts)])+' |')
        for layout in registered:
            cells=[NAMES[layout][lang]]
            cells.extend(pp(lookup.get((layout,c),{}).get('delta_J')).replace('缺失','missing') if lang else
                         pp(lookup.get((layout,c),{}).get('delta_J')) for c in contrasts)
            body.append('| '+' | '.join(cells)+' |')
        cells=['均值' if lang==0 else 'Mean']
        cells.extend(pp(aggregates[c]['metrics'].get('J',{}).get('mean')).replace('缺失','missing') if lang else
                     pp(aggregates[c]['metrics'].get('J',{}).get('mean')) for c in contrasts)
        body.append('| '+' | '.join(cells)+' |')
        body.append('')
    for name, zh_label, en_label in (
        ('global_main','区域全局主效应','Regional global main effect'),
        ('joint_vs_original','联合方案相对原方案','Combined method versus original'),
        ('joint_vs_frontier','联合方案相对严格最近可达前沿','Combined method versus strict nearest-reachable frontier'),
    ):
        metrics=aggregates[name]['metrics']
        zh.append(f'{zh_label}的首次跨房动作为 {describe(metrics,"first_new_room_paid",1,"步")}，'
                  f'重复边路程为 {describe(metrics,"repeat_distance_m",1,"m")}，'
                  f'达到 95% 覆盖的动作数为 {describe(metrics,"A95_paid",1,"步")}。')
        en.append(f'{en_label} changed the first inter-room arrival by {describe(metrics,"first_new_room_paid",1,"actions")}, '
                  f'repeated-edge travel by {describe(metrics,"repeat_distance_m",1,"m")}, '
                  f'and the 95% coverage clock by {describe(metrics,"A95_paid",1,"actions")}.')
    if counter:
        layout=counter['layout']
        old,new=report['minimum_pair_episodes']['original_G'],report['minimum_pair_episodes']['region_S']
        zh.extend(['',f'{NAMES[layout][0]}的联合策略降幅最大，J 变化为 {pp(counter["delta_J"])} 个百分点。'
                  f'正确自由区覆盖率为 {100*old["C_free"]:.2f}% 与 {100*new["C_free"]:.2f}%，'
                  f'表面 F1 为 {100*old["F1_scene_05cm"]:.2f}% 与 {100*new["F1_scene_05cm"]:.2f}%。'])
        en.extend(['',f'The smallest combined-versus-original difference occurred in the {NAMES[layout][1]} floor '
                  f'({pp(counter["delta_J"])} percentage points). Correct free-space coverage was '
                  f'{100*old["C_free"]:.2f}% versus {100*new["C_free"]:.2f}%, and scene F1 was '
                  f'{100*old["F1_scene_05cm"]:.2f}% versus {100*new["F1_scene_05cm"]:.2f}%.'])
        for pair in report['minimum_pair_divergence']:
            action=pair.get('first_action_difference_paid')
            dispatch=pair.get('first_dispatch_difference_paid')
            if dispatch is not None:
                outcomes=[pair['first_dispatch_'+arm+'_actual_outcome'] for arm in ('a','b')]
                origin=report['minimum_pair_first_dispatch'].get('region_S',{}).get('selection_origin')
                mechanism='区域层重排原有候选后，' if origin=='regional_rerank' else ''
                zh.append(f'{mechanism}两个策略在第 {dispatch} 步下发不同目标，'
                          f'原策略与联合策略的执行回执分别为 `{outcomes[0]}` 和 `{outcomes[1]}`。')
                en.append(f'The first different macro target was dispatched at action {dispatch}. '
                          f'The original and combined execution receipts were `{outcomes[0]}` and `{outcomes[1]}`.')
                if origin=='regional_rerank':
                    en.append('The regional layer changed the order of already feasible native candidates for this first decision.')
            if action is not None:
                zh.append(f'两臂首次实际动作分歧发生在第 {action} 步。')
                en.append(f'The first executed action diverged at action {action}.')
        if 'minimum_pair_J_delta_paid_48' in report:
            gap=pp(report['minimum_pair_J_delta_paid_48'])
            zh.append(f'到第 48 步，联合策略相对原策略的 J 差已为 {gap} 个百分点。')
            en.append(f'At the shared 48-action checkpoint, the combined-minus-original J difference was {gap} percentage points.')
    zh.extend(['','表中差值单位为百分点。方括号给出逐栋差值的最小值和最大值，'
               '阈值时间仅对相关策略均达标的楼层作数值差。样本单位是单栋楼层。'
               '实际到达、保护介入和终止原因见 [逐回合结果](episodes.csv) 与 [场景配对](first_divergence.csv)。'])
    en.extend(['','Table values are differences in percentage points. Brackets give the observed building-level range. '
               'Threshold times were differenced only for floors on which the relevant arms reached the threshold. '
               'One independent reporting unit was a floor. See [episodes](episodes.csv) and [paired traces](first_divergence.csv) '
               'for observed arrivals, guard interventions and stops.'])
    (output/'paper_zh.md').write_text('\n'.join(zh)+'\n')
    (output/'paper_en.md').write_text('\n'.join(en)+'\n')
    print('Bilingual measured results recorded.')


if __name__=='__main__':
    main()
